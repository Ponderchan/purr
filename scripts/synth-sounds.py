"""Synthesise purr.si cat sounds from scratch (no samples, no third-party audio).

Usage: python3 scripts/synth-sounds.py   (needs numpy and ffmpeg on PATH)
Writes src/assets/sound/*.mp3. Everything here is original, generated by code.

Models (source-filter, short-time spectral shaping):
- purr: laryngeal pulses ~23 Hz on inhale, ~26 Hz on exhale, breathing cycles of 2 s,
  shaped by low body resonances; loops seamlessly.
- hiss: band-passed air noise with a sharp onset.
- growl: rough low glottal pulse train with jitter/shimmer and low formants.
- trill: rolled "mrrp" with a rising pitch.
- meow: harmonic source with gliding pitch and formants moving i -> a -> u. Placeholder:
  a real recording will always sound better.
"""
import os
import subprocess
import numpy as np

SR = 44100
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "assets", "sound")
rng = np.random.default_rng(7)


def stft_shape(x, gain_fn, n=2048, hop=512):
    """Multiply each STFT frame by gain_fn(t_seconds, freqs) -> magnitude gains."""
    win = np.hanning(n)
    pad = np.concatenate([np.zeros(n), x, np.zeros(n)])
    out = np.zeros_like(pad)
    norm = np.zeros_like(pad)
    freqs = np.fft.rfftfreq(n, 1 / SR)
    for start in range(0, len(pad) - n, hop):
        frame = pad[start:start + n] * win
        t = (start + n / 2 - n) / SR
        spec = np.fft.rfft(frame) * gain_fn(max(t, 0.0), freqs)
        out[start:start + n] += np.fft.irfft(spec, n) * win
        norm[start:start + n] += win ** 2
    out = out / np.maximum(norm, 1e-8)
    return out[n:n + len(x)]


def peaks(freqs, centres, widths, levels):
    g = np.zeros_like(freqs)
    for c, w, l in zip(centres, widths, levels):
        g += l * np.exp(-0.5 * ((freqs - c) / w) ** 2)
    return g


def env(n, attack, release, sustain=1.0):
    e = np.full(n, sustain)
    a = int(attack * SR)
    r = int(release * SR)
    if a:
        e[:a] = sustain * 0.5 * (1 - np.cos(np.linspace(0, np.pi, a)))
    if r:
        e[-r:] *= 0.5 * (1 + np.cos(np.linspace(0, np.pi, r)))
    return e


def harmonic_source(f0, nharm=30, tilt=1.2):
    phase = 2 * np.pi * np.cumsum(f0) / SR
    s = np.zeros_like(f0)
    for k in range(1, nharm + 1):
        mask = (k * f0) < SR / 2 - 1000
        s += mask * np.sin(k * phase) / (k ** tilt)
    return s


def normalise(x, peak_db=-3.0):
    x = x - np.mean(x)
    return x / (np.max(np.abs(x)) + 1e-9) * 10 ** (peak_db / 20)


def purr():
    cycles, phases = 8, [("in", 0.85, 23.0), ("gap", 0.12, 0), ("out", 0.95, 26.0), ("gap", 0.08, 0)]
    parts_t, parts = [], []
    for _ in range(cycles):
        for kind, dur, rate in phases:
            n = int(dur * SR)
            if kind == "gap":
                parts.append(rng.normal(0, 0.004, n))
                continue
            sig = np.zeros(n)
            t = 0.0
            while t < dur:
                i = int(t * SR)
                L = int(0.014 * SR)
                burst = rng.normal(0, 1, L) * np.exp(-np.arange(L) / (0.005 * SR))
                burst[0] += 3.0
                amp = 1.0 + rng.normal(0, 0.15)
                end = min(n, i + L)
                sig[i:end] += amp * burst[: end - i]
                t += 1.0 / (rate * (1 + rng.normal(0, 0.04)))
            breath = rng.normal(0, 0.05 if kind == "in" else 0.03, n)
            sig = (sig + breath) * env(n, 0.16, 0.22)
            parts.append(sig * (0.85 if kind == "in" else 1.0))
    x = np.concatenate(parts)
    x = stft_shape(x, lambda t, f: peaks(f, [150, 320, 800, 2200], [80, 120, 250, 900], [1.0, 0.6, 0.18, 0.04]) * (f > 40))
    return normalise(x, -6.0)


def hiss():
    n = int(1.1 * SR)
    x = rng.normal(0, 1, n)
    x[: int(0.015 * SR)] *= 2.5
    e = env(n, 0.025, 0.3) * np.interp(np.arange(n), [0, n * 0.6, n], [1.0, 0.7, 0.6])
    x = stft_shape(x * e, lambda t, f: peaks(f, [4500, 7000, 2800], [1800, 1500, 600], [1.0, 0.6, 0.35]))
    return normalise(x, -4.0)


def growl():
    n = int(1.6 * SR)
    tt = np.arange(n) / SR
    f0 = np.interp(tt, [0, 0.5, 1.2, 1.6], [70, 86, 78, 62]) * (1 + rng.normal(0, 0.08, n).cumsum() / np.sqrt(np.arange(1, n + 1)) * 0.02)
    src = harmonic_source(f0, nharm=60, tilt=0.9)
    rough = 1 + 0.45 * np.sign(np.sin(2 * np.pi * np.cumsum(f0 / 2) / SR))
    am = 1 + 0.25 * np.sin(2 * np.pi * 18 * tt)
    x = src * rough * am + rng.normal(0, 0.15, n)
    x *= env(n, 0.2, 0.35)
    x = stft_shape(x, lambda t, f: peaks(f, [260, 720, 1500], [110, 200, 400], [1.0, 0.55, 0.15]))
    return normalise(x, -5.0)


def trill():
    n = int(0.45 * SR)
    tt = np.arange(n) / SR
    f0 = np.interp(tt, [0, 0.3, 0.45], [430, 640, 600])
    roll = 1 - 0.7 * (0.5 + 0.5 * np.sin(2 * np.pi * 28 * tt)) * (tt < 0.32)
    x = harmonic_source(f0, nharm=14, tilt=1.4) * roll + rng.normal(0, 0.02, n)
    x *= env(n, 0.03, 0.12)
    x = stft_shape(x, lambda t, f: peaks(f, [900, 2200, 3400], [250, 500, 700], [1.0, 0.45, 0.15]))
    return normalise(x, -5.0)


def meow(dur=0.75, f_hi=760, f_end=520, seed_shift=0.0):
    n = int(dur * SR)
    tt = np.arange(n) / SR
    f0 = np.interp(tt, [0, dur * 0.35, dur], [600 + seed_shift, f_hi + seed_shift, f_end + seed_shift])
    f0 *= 1 + 0.012 * np.sin(2 * np.pi * 5.5 * tt)
    x = harmonic_source(f0, nharm=16, tilt=1.1) + rng.normal(0, 0.03, n)
    x *= env(n, 0.04, 0.22)

    def formants(t, f):
        p = min(t / dur, 1.0)
        f1 = np.interp(p, [0, 0.3, 0.7, 1], [320, 820, 800, 420])
        f2 = np.interp(p, [0, 0.3, 0.7, 1], [2300, 1450, 1300, 900])
        return peaks(f, [f1, f2, 3000], [110, 220, 400], [1.0, 0.65, 0.2]) + 0.02

    return normalise(stft_shape(x, formants), -5.0)


def write_mp3(name, x):
    os.makedirs(OUT, exist_ok=True)
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2").tobytes()
    path = os.path.join(OUT, name)
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "s16le", "-ar", str(SR), "-ac", "1", "-i", "-",
         "-codec:a", "libmp3lame", "-q:a", "4", path],
        input=pcm, check=True,
    )
    print(name, f"{len(x) / SR:.2f}s")


if __name__ == "__main__":
    write_mp3("purr-loop.mp3", purr())
    write_mp3("hiss.mp3", hiss())
    write_mp3("growl.mp3", growl())
    write_mp3("trill.mp3", trill())
    write_mp3("meow-happy-1.mp3", meow())
    write_mp3("meow-happy-2.mp3", meow(dur=0.55, f_hi=820, f_end=640, seed_shift=40))
